# 面板B事件锚定到周线
PANEL_B = []
for d, kind, t, desc in PB_RAW:
    wk = wk_of(d)
    if wk is None:
        continue
    # 事件点 y 值: 用该周的相关极值(顶用high, 底用low, 其他用close)
    if kind == 'peak':
        y = wk['h']
    elif kind in ('start',) and ('底' in t or '低' in t):
        y = wk['l']
    else:
        y = wk['c']
    PANEL_B.append(dict(date=d, wk_date=wk['date'], kind=kind, t=t, d=desc, y=round(y, 2)))

